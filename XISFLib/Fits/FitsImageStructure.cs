using System.Globalization;

namespace XISFLib;

internal static class FitsImageStructure
{
    public static bool IsStructural(string keyword) => keyword.ToUpperInvariant() is "SIMPLE" or "XTENSION" or "PCOUNT" or "GCOUNT" or "EXTEND" or "BITPIX" or "NAXIS" or "BSCALE" or "BZERO" or "BLANK" or "CHECKSUM" or "DATASUM" || keyword.StartsWith("NAXIS", StringComparison.OrdinalIgnoreCase);

    public static void ValidateCard(FitsHeaderCard card, FitsImage image, FitsHduType type)
    {
        string key = card.Keyword.ToUpperInvariant();
        if (key is "CHECKSUM" or "DATASUM" or "EXTEND") throw new InvalidOperationException($"'{key}' is generated by FitsWriter; configure FitsWriterOptions instead.");
        if (key is "SIMPLE" or "XTENSION")
        {
            bool valid = key == "SIMPLE" ? type == FitsHduType.Primary && card.Value is true : type == FitsHduType.Image && card.Value is "IMAGE";
            if (!valid) throw new InvalidOperationException($"'{key}' is defined by the HDU type.");
            return;
        }
        object? expected = key switch
        {
            "BITPIX" => image.BitPix, "NAXIS" => image.Dimensions.Count,
            "BSCALE" => image.BScale, "BZERO" => image.BZero, "BLANK" => image.Blank, "PCOUNT" => 0, "GCOUNT" => 1,
            _ => null
        };
        bool check = key is "BITPIX" or "NAXIS" or "BSCALE" or "BZERO" or "BLANK" or "PCOUNT" or "GCOUNT";
        if (key.StartsWith("NAXIS", StringComparison.Ordinal) && key != "NAXIS")
        {
            check = true;
            if (int.TryParse(key.AsSpan(5), out int axis) && axis >= 1 && axis <= image.Dimensions.Count) expected = image.Dimensions[axis - 1];
        }
        if (!check) return;
        bool equal = expected is null ? card.Value is null : card.Value is not null &&
            (expected is long ? Convert.ToDecimal(card.Value, CultureInfo.InvariantCulture) == Convert.ToDecimal(expected, CultureInfo.InvariantCulture) : Convert.ToDouble(card.Value, CultureInfo.InvariantCulture) == Convert.ToDouble(expected, CultureInfo.InvariantCulture));
        if (!equal) throw new InvalidOperationException($"'{card.Keyword}' is defined by image storage. Use FitsHdu.ReplaceImage with the required geometry or scaling.");
    }
}
